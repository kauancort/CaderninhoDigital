-- Categorias normalizadas e SKU opcionais mantêm compatibilidade com o catálogo legado.
CREATE TABLE categorias_produto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    descricao VARCHAR(500),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    categoria_pai_id BIGINT,
    criado_em TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_categoria_pai FOREIGN KEY (categoria_pai_id) REFERENCES categorias_produto (id),
    CONSTRAINT uk_categoria_nome UNIQUE (nome)
);

ALTER TABLE produtos ADD COLUMN sku VARCHAR(60);
ALTER TABLE produtos ADD COLUMN categoria_id BIGINT;
ALTER TABLE produtos ADD CONSTRAINT fk_produtos_categoria FOREIGN KEY (categoria_id) REFERENCES categorias_produto (id);
CREATE UNIQUE INDEX uk_produtos_sku_global ON produtos (LOWER(sku)) WHERE sku IS NOT NULL;
CREATE INDEX idx_produtos_categoria_nome ON produtos (categoria_id, nome);

CREATE TABLE historico_precos_produto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id BIGINT NOT NULL,
    preco NUMERIC(12,2) NOT NULL,
    inicio_vigencia TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    fim_vigencia TIMESTAMP(6) WITHOUT TIME ZONE,
    usuario_id BIGINT,
    alterado_em TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    motivo VARCHAR(500),
    origem VARCHAR(60) NOT NULL,
    CONSTRAINT fk_hist_preco_produto FOREIGN KEY (produto_id) REFERENCES produtos (id),
    CONSTRAINT fk_hist_preco_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
);

CREATE TABLE historico_custos_materia_prima (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    materia_prima_id BIGINT NOT NULL,
    custo NUMERIC(12,2) NOT NULL,
    inicio_vigencia TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    fim_vigencia TIMESTAMP(6) WITHOUT TIME ZONE,
    usuario_id BIGINT,
    alterado_em TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    motivo VARCHAR(500),
    origem VARCHAR(60) NOT NULL,
    CONSTRAINT fk_hist_custo_materia FOREIGN KEY (materia_prima_id) REFERENCES materias_primas (id),
    CONSTRAINT fk_hist_custo_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
);

