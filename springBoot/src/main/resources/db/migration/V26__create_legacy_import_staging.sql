    ADD CONSTRAINT ck_movimentacoes_origem CHECK (
        origem IN ('CADASTRO', 'COMPRA', 'PRODUCAO', 'VENDA', 'AJUSTE_MANUAL', 'REMOCAO_MANUAL', 'MIGRACAO')
